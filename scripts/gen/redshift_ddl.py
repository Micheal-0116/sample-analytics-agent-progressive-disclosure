#!/usr/bin/env python3
"""从 Postgres DDL 生成 Redshift 方言 DDL（含 DISTKEY / SORTKEY）。

## 为什么要生成而不是手写一份

`database/01-08_*.sql` 是表结构的真源。手抄一份 Redshift 版就等于开了第二个真源，
下次改列必然漂移。这里从同一份 DDL 解析后转换，改列只改一处。

## Postgres → Redshift 的不兼容点（逐条处理）

| Postgres | Redshift | 说明 |
|---|---|---|
| `JSONB` / `JSON` | `SUPER` | Redshift 没有 JSONB；SUPER 能存半结构化并用 PartiQL 查 |
| `TEXT[]` / `BIGINT[]` | `SUPER` | Redshift 没有数组类型 |
| `SERIAL` / `BIGSERIAL` | `INTEGER` / `BIGINT` | 没有序列；主键值由生成器给定 |
| `TEXT` | `VARCHAR(65535)` | Redshift 无无界 TEXT，65535 是上限 |
| `VARCHAR(n)` | `VARCHAR(n*4)` | **Redshift 的长度按字节算，不是字符**。中文一字 3 字节，`VARCHAR(50)` 装不下 50 个汉字，COPY 会报 "value too long"。统一放大 4 倍 |
| `CREATE INDEX` | 丢弃 | Redshift 没有二级索引，用 SORTKEY 替代 |
| `PRIMARY KEY` / `REFERENCES` | 保留但不强制 | Redshift 接受但不校验，仅供优化器参考 |

## DISTKEY / SORTKEY

这是 Redshift 相对 Postgres 真正多出来的东西，也是行数上到千万级才有意义的部分：
- 大事实表按 `user_id` 分布 → 与 `users` 同键的 join 变成本地 join，不走网络重分发
- 按时间列排序 → 时间范围过滤（几乎每道分析题都有）可以跳过大部分数据块
- 维度表用 `DISTSTYLE ALL` → 每个节点各存一份，join 永远本地
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import ddl  # noqa: E402

# 大事实表的分布/排序键。选 user_id 分布是为了让「用户维度的 join」本地化。
DIST_SORT = {
    "users":                ("user_id", "registered_at"),
    "user_profiles":        ("user_id", "user_id"),
    "user_devices":         ("user_id", "first_seen_at"),
    "user_segment_members": ("user_id", "entered_at"),
    "sessions":             ("user_id", "start_time"),
    "events":               ("user_id", "event_time"),
    "page_views":           ("user_id", "view_time"),
    "posts":                ("post_id", "published_at"),
    "post_likes":           ("post_id", "created_at"),
    "post_comments":        ("post_id", "created_at"),
    "post_shares":          ("post_id", "created_at"),
    "user_follows":         ("follower_id", "created_at"),
    "user_messages":        ("sender_id", "sent_at"),
    "orders":               ("user_id", "placed_at"),
    "order_items":          ("order_id", "order_id"),
    "payments":             ("user_id", "created_at"),
    "subscriptions":        ("user_id", "start_date"),
    "user_attributions":    ("user_id", "click_time"),
    "user_coupons":         ("user_id", "received_at"),
    "push_notifications":   ("user_id", "scheduled_at"),
    "ab_test_assignments":  ("user_id", "assigned_at"),
}

# 维度表：每节点各存一份，join 永远本地（行数都在几百到几千，代价可忽略）
DIST_ALL = ["categories", "products", "product_tags", "channels", "event_definitions",
            "user_segments", "campaigns", "coupons", "banners", "ab_tests",
            "ab_test_variants", "ad_campaigns", "ad_creatives", "channel_daily_costs"]

VARCHAR_BYTE_FACTOR = 4          # 见模块 docstring：Redshift VARCHAR 按字节计长
MAX_VARCHAR = 65535


def map_type(raw: str) -> str:
    t = raw.strip()
    up = t.upper()
    if "[]" in up.split()[0]:
        return "SUPER"
    if up.startswith(("JSONB", "JSON")):
        return "SUPER"
    if up.startswith("BIGSERIAL"):
        return "BIGINT"
    if up.startswith("SERIAL"):
        return "INTEGER"
    if up.startswith("TEXT"):
        return f"VARCHAR({MAX_VARCHAR})"
    m = re.match(r"(?i)^(VARCHAR|CHARACTER VARYING|CHAR)\s*\(\s*(\d+)\s*\)", t)
    if m:
        n = min(int(m.group(2)) * VARCHAR_BYTE_FACTOR, MAX_VARCHAR)
        return f"VARCHAR({n})"
    if up.startswith(("VARCHAR", "CHAR")):
        return f"VARCHAR({MAX_VARCHAR})"
    m = re.match(r"(?i)^(DECIMAL|NUMERIC)\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)", t)
    if m:
        return f"DECIMAL({m.group(2)},{m.group(3)})"
    if up.startswith(("DECIMAL", "NUMERIC")):
        return "DECIMAL(18,4)"
    if up.startswith("DOUBLE"):
        return "DOUBLE PRECISION"
    if up.startswith("REAL"):
        return "REAL"
    if up.startswith("SMALLINT"):
        return "SMALLINT"
    if up.startswith("BIGINT"):
        return "BIGINT"
    if up.startswith(("INTEGER", "INT")):
        return "INTEGER"
    if up.startswith("BOOLEAN"):
        return "BOOLEAN"
    if up.startswith("TIMESTAMP"):
        return "TIMESTAMP"
    if up.startswith("DATE"):
        return "DATE"
    return f"VARCHAR({MAX_VARCHAR})"


def render(tables: dict[str, list[tuple[str, str, str]]]) -> str:
    out = [
        "-- ⚙️ generated by scripts/gen/redshift_ddl.py from database/01-08_*.sql",
        "-- DO NOT EDIT —— 改表结构请改 Postgres DDL 后重跑本脚本。",
        "-- 转换规则与 DISTKEY/SORTKEY 选型见 redshift_ddl.py 的模块 docstring。",
        "",
    ]
    for name in sorted(tables):
        cols = tables[name]
        out.append(f"DROP TABLE IF EXISTS {name} CASCADE;")
        lines = [f"CREATE TABLE {name} ("]
        body = [f"    {c:<24} {map_type(raw)}" for c, raw, _ in cols]
        lines.append(",\n".join(body))
        tail = ")"
        if name in DIST_ALL:
            tail += "\nDISTSTYLE ALL"
        elif name in DIST_SORT:
            dk, sk = DIST_SORT[name]
            have = {c for c, _, _ in cols}
            if dk in have:
                tail += f"\nDISTKEY({dk})"
            if sk in have:
                tail += f"\nSORTKEY({sk})"
        lines.append(tail + ";")
        out.append("\n".join(lines))
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="写到文件；省略则打印")
    a = ap.parse_args()
    sql = render(ddl.parse_all_raw())
    if a.out:
        Path(a.out).write_text(sql)
        print(f"→ {a.out}  ({len(sql.splitlines())} 行)")
    else:
        print(sql)
